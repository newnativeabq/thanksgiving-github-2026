import { readFile } from 'node:fs/promises';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standalone from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';

const schema = JSON.parse(await readFile(new URL('../docs/recipe-import-v1.schema.json', import.meta.url), 'utf8'));
const ajv = new Ajv2020({ allErrors: true, code: { source: true, esm: true } });
addFormats(ajv, ['uri']);
const units = schema.$defs.ingredient.properties.unit.enum;
const contents = standalone(ajv, ajv.compile(schema)) + '\nexport const RECIPE_UNITS = ' + JSON.stringify(units) + ';';
await build({
  stdin: { contents, resolveDir: new URL('..', import.meta.url).pathname },
  outfile: new URL('../recipe-validator.generated.js', import.meta.url).pathname,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  minify: true,
  banner: { js: '// Generated by npm run build:recipe from docs/recipe-import-v1.schema.json.' },
});
